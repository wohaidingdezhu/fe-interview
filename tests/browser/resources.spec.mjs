import { test, expect } from '@playwright/test';

test('相关资料独立分类、搜索与详情返回保持栏目', async ({ page }) => {
  await page.goto('/?view=resources');
  await expect(page.getByRole('heading', { level: 1, name: '相关资料' })).toBeVisible();
  await expect(page.locator('.resource-card')).toHaveCount(6);
  const sidebar = page.getByRole('complementary', { name: '资料库导航' });
  if (!await sidebar.isVisible()) await page.getByRole('button', { name: '打开导航', exact: true }).click();
  await expect(sidebar.getByRole('navigation', { name: '资料库入口' }).getByRole('link', { name: '相关资料', exact: true })).toHaveClass(/active/);
  await sidebar.getByRole('navigation', { name: '分类导航' }).getByRole('link', { name: '工程实践', exact: true }).click();
  await expect(page.locator('.resource-card')).toHaveCount(2);
  expect(new URL(page.url()).searchParams.get('view')).toBe('resources');
  const search = page.getByRole('searchbox', { name: '检索当前列表' });
  await search.fill('FlowUIRegistry');
  await expect(page.locator('.resource-card')).toHaveCount(1);
  await page.locator('.resource-card h2 a').click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('FlowUIService：通过 Schema 从服务层调用弹窗');
  const breadcrumb = page.getByRole('navigation', { name: '面包屑', exact: true });
  await expect(breadcrumb.getByRole('link', { name: '相关资料', exact: true })).toHaveAttribute('href', '?view=resources');
  await expect(breadcrumb.getByRole('link', { name: '工程实践', exact: true })).toHaveAttribute('href', /view=resources&category=/);
  await expect(page.locator('.article-body img')).toHaveCount(5);
  const images = await page.locator('.article-body img').evaluateAll(images => images.map(image => image.src));
  for (const url of images) expect((await page.request.get(url)).status()).toBe(200);
  await breadcrumb.getByRole('link', { name: '工程实践', exact: true }).click();
  await expect(page.locator('.resource-card')).toHaveCount(2);
  await search.fill('没有这份资料');
  await expect(page.getByRole('heading', { name: '没有找到匹配内容' })).toBeVisible();
  await page.getByRole('link', { name: '查看全部相关资料 →', exact: true }).click();
  await expect(page.locator('.resource-card')).toHaveCount(6);
  await page.goto('/?view=notes&collection=notes');
  await expect(page.locator('.resource-card h2 a[href=\"?article=zsh-custom-config\"], .resource-card h2 a[href=\"?article=flow-ui-service-schema\"]')).toHaveCount(0);
});

test('资料外链新标签、收藏图片可放大、静态深链接可刷新', async ({ page }, testInfo) => {
  await page.goto('/articles/zsh-custom-config/');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Oh My Zsh 配置收藏与自动建议');
  const external = page.locator('.article-body').getByRole('link', { name: 'oh-my-zsh-custom-xxf：自定义主题与配置' });
  await expect(external).toHaveAttribute('target', '_blank');
  await expect(external).toHaveAttribute('rel', 'noopener noreferrer');
  await page.reload();
  await page.getByRole('navigation', { name: '面包屑' }).getByRole('link', { name: '相关资料', exact: true }).click();
  await page.locator('.resource-card h2 a').filter({ hasText: '生活摘录' }).click();
  const picture = page.getByRole('button', { name: /^放大图片：关于外界干扰/ });
  await picture.click();
  const preview = page.getByRole('dialog', { name: '图片预览', exact: true });
  await expect(preview.getByRole('img')).toBeVisible();
  await expect(preview.getByRole('img')).toHaveJSProperty('naturalWidth', 1181);
  await preview.getByRole('button', { name: '放大', exact: true }).click();
  await expect(preview.getByRole('button', { name: '适应窗口', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.keyboard.press('Escape');
  await expect(preview).not.toBeVisible();
  await expect(picture).toBeFocused();
  await page.screenshot({ path: testInfo.outputPath('related-article.png') });
  const global = page.getByRole('searchbox', { name: '搜索题目和笔记' });
  await global.fill('UIServiceVitestImpl');
  await page.locator('.search-results').getByRole('link', { name: /用 Inversify 替换 UI 服务/ }).click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('用 Inversify 替换 UI 服务，让业务逻辑更容易测试');
  expect(page.context().pages()).toHaveLength(1);
});
